public class vari {
    public static void main(String[] args) {
        int a = 10;
        double b = 25.5;
        char c = 'A';
        boolean d = true;

        System.out.println("int = " + a);
        System.out.println("double = " + b);
        System.out.println("char = " + c);
        System.out.println("boolean = " + d);
    }
}